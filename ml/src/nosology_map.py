# Обратный поиск: из любой нозологии → основная группа
def get_nosology_group(nosology: str) -> str:
    """
    Возвращает основную группу для данной нозологии (или саму нозологию, если группы нет).
    """
    if not nosology:
        return ""

    nos = nosology.lower().strip()

    for group, synonyms in NOSOLOGY_GROUPS.items():
        if nos in [s.lower() for s in synonyms]:
            return group

    # Если точного матча нет — возвращаем как есть
    return nos


def get_synonyms_for_group(group: str) -> List[str]:
    """Возвращает все синонимы для группы"""
    return NOSOLOGY_GROUPS.get(group, [])


def get_all_synonyms(nosology: str) -> List[str]:
    """Для данной нозологии возвращает все возможные синонимы (включая группу)"""
    group = get_nosology_group(nosology)
    return [nosology] + get_synonyms_for_group(group)